let currentLang = localStorage.getItem("linkedu_lang") || "fr";

// Fonction de traduction globale exposée sur window
window.applyLanguage = function(lang) {
  currentLang = lang;
  localStorage.setItem("linkedu_lang", lang);
  document.documentElement.lang = lang;

  const dict = window.translations[lang] || window.translations.fr;

  // 1. Traduction des textes normaux ([data-i18n])
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict && dict[key]) {
      if (dict[key].includes("<")) {
        el.innerHTML = dict[key];
      } else {
        el.textContent = dict[key];
      }
    }
  });

  // 2. Traduction des placeholders ([data-i18n-placeholder])
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dict && dict[key]) {
      el.placeholder = dict[key];
    }
  });

  const langTextDesktop = document.getElementById("langTextDesktop");
  const langToggleBurger = document.getElementById("langToggleBurger");

  if (langTextDesktop) {
    langTextDesktop.textContent = lang === "fr" ? dict.lang_desktop_fr : dict.lang_desktop_en;
  }
  if (langToggleBurger) {
    langToggleBurger.innerHTML = lang === "fr" ? dict.lang_burger_en : dict.lang_burger_fr;
  }

  if (typeof loadAnnouncements === "function") {
    loadAnnouncements();
  }
};

