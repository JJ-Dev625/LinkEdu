// CODE PRINCIPAL AU CHARGEMENT DE LA PAGE
// ==========================================
document.addEventListener("DOMContentLoaded", () => {

  // 1. GESTION DES MENUS DÉROULANTS (Connexion / Inscription)
  const btnConnexion = document.getElementById("btnConnexionToggle");
  const menuConnexion = document.getElementById("menuConnexion");
  const arrowConnexion = document.getElementById("arrowConnexion");

  const btnInscription = document.getElementById("btnInscriptionToggle");
  const menuInscription = document.getElementById("menuInscription");
  const arrowInscription = document.getElementById("arrowInscription");

  if (btnConnexion && menuConnexion) {
    btnConnexion.addEventListener("click", (e) => {
      e.stopPropagation();
      if (menuInscription) {
        menuInscription.style.setProperty("display", "none", "important");
        if (arrowInscription) arrowInscription.style.transform = "rotate(0deg)";
      }
      const isOpen = menuConnexion.style.display === "block" || menuConnexion.style.display === "flex";
      if (isOpen) {
        menuConnexion.style.setProperty("display", "none", "important");
        if (arrowConnexion) arrowConnexion.style.transform = "rotate(0deg)";
      } else {
        menuConnexion.style.setProperty("display", "block", "important");
        if (arrowConnexion) arrowConnexion.style.transform = "rotate(180deg)";
      }
    });
  }

  if (btnInscription && menuInscription) {
    btnInscription.addEventListener("click", (e) => {
      e.stopPropagation();
      if (menuConnexion) {
        menuConnexion.style.setProperty("display", "none", "important");
        if (arrowConnexion) arrowConnexion.style.transform = "rotate(0deg)";
      }
      const isOpen = menuInscription.style.display === "block" || menuInscription.style.display === "flex";
      if (isOpen) {
        menuInscription.style.setProperty("display", "none", "important");
        if (arrowInscription) arrowInscription.style.transform = "rotate(0deg)";
      } else {
        menuInscription.style.setProperty("display", "block", "important");
        if (arrowInscription) arrowInscription.style.transform = "rotate(180deg)";
      }
    });
  }

  window.addEventListener("click", (e) => {
    if (menuConnexion) {
      menuConnexion.style.setProperty("display", "none", "important");
      if (arrowConnexion) arrowConnexion.style.transform = "rotate(0deg)";
    }
    if (menuInscription) {
      menuInscription.style.setProperty("display", "none", "important");
      if (arrowInscription) arrowInscription.style.transform = "rotate(0deg)";
    }
  });

  // 2. DIAPORAMA D'ARRIÈRE-PLAN (Hero Slider)
  const heroSlider = document.querySelector(".hero-left-card");
  const imagesList = [
    './images/etu1.jpg', './images/etu2.jpg', './images/el1.jpg',
    './images/el2.jpg', './images/ens.jpg', './images/pri1.jpg',
    './images/el3.jpg', './images/etu3.jpg', './images/ens2.jpg'
  ];

  if (heroSlider && imagesList.length > 0) {
    let currentImageIndex = 0;

    imagesList.forEach((src, index) => {
      const img = document.createElement('img');
      img.src = src;
      img.className = 'bg-slide';
      img.style.position = 'absolute';
      img.style.top = '0';
      img.style.left = '0';
      img.style.width = '100%';
      img.style.height = '100%';
      img.style.objectFit = 'cover';
      img.style.filter = 'brightness(0.55)';
      img.style.opacity = index === 0 ? '1' : '0';
      img.style.transition = 'opacity 1.5s ease-in-out';
      img.style.zIndex = '1';
      heroSlider.appendChild(img);
    });

    Array.from(heroSlider.children).forEach(child => {
      if (!child.classList.contains('bg-slide')) {
        child.style.position = 'relative';
        child.style.zIndex = '2';
      }
    });

    setInterval(() => {
      const imgs = heroSlider.querySelectorAll('.bg-slide');
      if (imgs.length > 0) {
        imgs[currentImageIndex].style.opacity = '0';
        currentImageIndex = (currentImageIndex + 1) % imgs.length;
        imgs[currentImageIndex].style.opacity = '1';
      }
    }, 8000);
  }

  // 3. GESTION DU MODE SOMBRE / CLAIR & LOGOS
  const darkModeToggleDesktop = document.getElementById("darkModeToggleDesktop");
  const darkModeToggleBurger = document.getElementById("darkModeToggle");
  const body = document.body;

  const savedTheme = localStorage.getItem("linkedu_theme");
  
  function applyTheme(isDark) {
    if (isDark) {
      body.classList.add("dark-mode");
      if (darkModeToggleDesktop) {
        darkModeToggleDesktop.innerHTML = `<i class="fa-solid fa-sun"></i> <span data-i18n="nav_theme">${window.translations[currentLang].nav_theme || 'Thème'}</span>`;
      }
      if (darkModeToggleBurger) darkModeToggleBurger.innerHTML = window.translations[currentLang].theme_light;
      localStorage.setItem("linkedu_theme", "dark");
    } else {
      body.classList.remove("dark-mode");
      if (darkModeToggleDesktop) {
        darkModeToggleDesktop.innerHTML = `<i class="fa-solid fa-moon"></i> <span data-i18n="nav_theme">${window.translations[currentLang].nav_theme || 'Thème'}</span>`;
      }
      if (darkModeToggleBurger) darkModeToggleBurger.innerHTML = window.translations[currentLang].theme_dark;
      localStorage.setItem("linkedu_theme", "light");
    }
  }

  if (savedTheme === "dark") {
    applyTheme(true);
  } else {
    applyTheme(false);
  }

  function handleThemeToggle(e) {
    if (e) e.preventDefault();
    const isDarkMode = !body.classList.contains("dark-mode");
    applyTheme(isDarkMode);
  }

  if (darkModeToggleDesktop) darkModeToggleDesktop.addEventListener("click", handleThemeToggle);
  if (darkModeToggleBurger) darkModeToggleBurger.addEventListener("click", handleThemeToggle);

  // 4. GESTION DE LA BASCULE DE LANGUE
  const langToggleDesktop = document.getElementById("langToggleDesktop");
  const langToggleBurger = document.getElementById("langToggleBurger");

  function handleLangToggle(e) {
    if (e) e.preventDefault();
    const newLang = currentLang === "fr" ? "en" : "fr";
    window.applyLanguage(newLang);
    applyTheme(body.classList.contains("dark-mode"));
  }

  if (langToggleDesktop) langToggleDesktop.addEventListener("click", handleLangToggle);
  if (langToggleBurger) langToggleBurger.addEventListener("click", handleLangToggle);

  window.applyLanguage(currentLang);

  // 5. GESTION DU MENU BURGER MOBILE
  const burgerToggle = document.getElementById("burgerToggle");
  const burgerMenu = document.getElementById("burgerMenu");
  const burgerClose = document.getElementById("burgerClose");
  const burgerOverlay = document.getElementById("burgerOverlay");

  function toggleBurger() {
    if (burgerMenu) burgerMenu.classList.toggle("active");
    if (burgerOverlay) burgerOverlay.classList.toggle("active");
  }

  if (burgerToggle) burgerToggle.addEventListener("click", toggleBurger);
  if (burgerClose) burgerClose.addEventListener("click", toggleBurger);
  if (burgerOverlay) burgerOverlay.addEventListener("click", toggleBurger);

  // 6. BANDEAU D'ANNONCES DYNAMIQUE (Ticker)
  window.loadAnnouncements = function() {
    const tickerTrack = document.getElementById("homeAnnouncementsTicker");
    if (!tickerTrack) return;

    let rawData = localStorage.getItem("adminAnnouncements") || localStorage.getItem("announcements") || localStorage.getItem("linkedu_annonces");
    let adminAnnouncements = [];
    
    try {
      adminAnnouncements = JSON.parse(rawData) || [];
    } catch (err) {
      adminAnnouncements = [];
    }

    if (!Array.isArray(adminAnnouncements) || adminAnnouncements.length === 0) {
      adminAnnouncements = [
        window.translations[currentLang].announcement_default_1,
        window.translations[currentLang].announcement_default_2
      ];
    }

    tickerTrack.innerHTML = adminAnnouncements.map(item => {
      let text = typeof item === 'object' && item !== null ? (item.message || item.texte || item.content || JSON.stringify(item)) : item;
      return `<span class="ticker-item"><i class="fa-solid fa-bullhorn"></i> ${text}</span>`;
    }).join('');
  };

  window.loadAnnouncements();

});
